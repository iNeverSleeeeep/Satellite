function q_bi = triad_attitude_init(sun_b, mag_b, sun_i, mag_i)
%TRIAD_ATTITUDE_INIT 使用 TRIAD 方法由两组方向矢量直接求解姿态。
%
% 输入:
%   sun_b : 机体系下太阳敏感器测得的太阳方向。
%   mag_b : 机体系下磁力计测得的地磁方向。
%   sun_i : 惯性系下太阳参考方向。
%   mag_i : 惯性系下地磁参考方向。
%
% 输出:
%   q_bi  : 机体系相对惯性系的姿态四元数。
%
% 核心思想:
%   TRIAD 是经典的两矢量姿态确定方法。已知两组“同一物理方向”在不同
%   坐标系下的表达，就可以分别在两个坐标系中构造一组正交基，然后求得
%   两组基之间的旋转矩阵，最终得到姿态。
%
% 这四个向量分别代表什么:
%   1. sun_b 和 mag_b
%      由实际传感器给出，表示太阳方向和局部地磁方向在机体系下的表达。
%   2. sun_i 和 mag_i
%      由环境参考模型给出，表示同样两个物理方向在惯性系下的表达。
%
%   TRIAD 并不要求知道“整个地球磁场的全局形状”，它只要求知道:
%   同一个物理方向，在机体系和惯性系中的对应表达。
%   因此，磁力计给出的“卫星当前位置局部磁场切线方向”完全可以作为 TRIAD
%   的参考向量之一。
%
% 正式工程里 sun_i 和 mag_i 从哪来:
%   1. sun_i 通常由时间系统和太阳星历/天文模型计算得到。
%   2. mag_i 通常由卫星当前位置、时间以及地磁场模型计算得到。
%   3. 也就是说，正式工程中它们通常仍然来自环境参考模型，只是模型精度会
%      明显高于当前工程中的简化版本。
%
% 为什么这些参考向量一般不会像积分那样长期漂移:
%   1. TRIAD 本身不是积分算法，它每次都是根据当前时刻的向量直接解姿态。
%   2. sun_i 和 mag_i 通常也是按“当前绝对时间 + 当前轨道位置”直接求值，
%      而不是由上一时刻积分递推得到。
%   3. 因此它们通常不会出现陀螺积分那种误差随时间不断积累的漂移。
%   4. 真正会出现的是“模型误差”或“参考误差”，例如太阳模型简化、地磁模型
%      近似、时间不准、轨道位置不准、坐标系转换误差等。
%
% 具体步骤:
%   1. 在机体系中，以太阳方向为第一基向量。
%   2. 利用太阳方向与磁场方向叉乘，构造第二基向量。
%   3. 再由前两项叉乘得到第三基向量，形成机体系 TRIAD。
%   4. 在惯性系中重复上述过程，形成惯性系 TRIAD。
%   5. 由 DCM_bi = T_b * T_i' 得到姿态矩阵，再转为四元数。
%
% t1_b、t2_b、t3_b 的物理意义:
%   1. t1_b
%      机体系下第一基向量，这里直接选为太阳方向。
%      物理上表示“卫星机体系中太阳来的方向”。
%   2. t2_b
%      由 sun_b 和 mag_b 的叉乘得到，垂直于“太阳方向-地磁方向”张成的平面。
%      物理上表示由这两个参考方向共同定义出的法向方向。
%   3. t3_b
%      由 t1_b 和 t2_b 再次叉乘得到，用于补齐右手正交基。
%
% 注意:
%   若太阳方向与磁场方向近似共线，则两矢量法退化，此时无法稳定确定姿态。
%   这是因为只有一根独立方向轴时，绕该轴的旋转无法唯一确定。

sun_b = local_unit_vector(sun_b);
mag_b = local_unit_vector(mag_b);
sun_i = local_unit_vector(sun_i);
mag_i = local_unit_vector(mag_i);

if norm(cross(sun_b, mag_b)) < 1e-8 || norm(cross(sun_i, mag_i)) < 1e-8
    q_bi = [1.0; 0.0; 0.0; 0.0];
    return;
end

t1_b = sun_b;
t2_b = local_unit_vector(cross(sun_b, mag_b));
t3_b = cross(t1_b, t2_b);

t1_i = sun_i;
t2_i = local_unit_vector(cross(sun_i, mag_i));
t3_i = cross(t1_i, t2_i);

DCM_bi = [t1_b, t2_b, t3_b] * [t1_i, t2_i, t3_i]';
q_bi = dcm2q(DCM_bi);
end